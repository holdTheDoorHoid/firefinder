def flag_coordinate(abbr: str, lat: float, lon: float) -> str | None:
    """Returns a short problem code, or None if the coordinate looks plausible."""
    if lon > 0:
        return "lon_positive_sign"
    if lat < 0:
        return "lat_negative_sign"
    box = STATE_BBOX.get(abbr.upper())
    if box is None:
        return None
    lat_min, lat_max, lon_min, lon_max = box
    if not (lat_min <= lat <= lat_max and lon_min <= lon <= lon_max):
        return "outside_state_bbox"
    return None
